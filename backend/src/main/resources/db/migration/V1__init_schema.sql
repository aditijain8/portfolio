-- Portable between PostgreSQL (production) and H2 in PostgreSQL mode (tests).

CREATE TABLE admin_user (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(254) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_admin_email UNIQUE (email)
);

CREATE TABLE stored_file (
    storage_key VARCHAR(80) PRIMARY KEY,
    content     BYTEA NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE media (
    id                VARCHAR(36) PRIMARY KEY,
    storage_key       VARCHAR(80) NOT NULL,
    content_type      VARCHAR(50) NOT NULL,
    size_bytes        BIGINT NOT NULL,
    original_filename VARCHAR(255),
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE project (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title             VARCHAR(160) NOT NULL,
    slug              VARCHAR(120) NOT NULL,
    summary           VARCHAR(500),
    description       TEXT,
    problem_statement TEXT,
    architecture      TEXT,
    contributions     TEXT,
    challenges        TEXT,
    lessons_learned   TEXT,
    github_url        VARCHAR(500),
    demo_url          VARCHAR(500),
    cover_image_id    VARCHAR(36),
    category          VARCHAR(80),
    start_year        INT,
    status            VARCHAR(20) NOT NULL,
    featured          BOOLEAN NOT NULL DEFAULT FALSE,
    published         BOOLEAN NOT NULL DEFAULT FALSE,
    display_order     INT NOT NULL DEFAULT 0,
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_project_slug UNIQUE (slug)
);
CREATE INDEX idx_project_published_order ON project (published, display_order);
CREATE INDEX idx_project_category ON project (category);

CREATE TABLE project_technology (
    project_id BIGINT NOT NULL REFERENCES project (id) ON DELETE CASCADE,
    position   INT NOT NULL,
    name       VARCHAR(60) NOT NULL,
    PRIMARY KEY (project_id, position)
);
CREATE INDEX idx_project_tech_name ON project_technology (name);

CREATE TABLE project_feature (
    project_id BIGINT NOT NULL REFERENCES project (id) ON DELETE CASCADE,
    position   INT NOT NULL,
    feature    VARCHAR(500) NOT NULL,
    PRIMARY KEY (project_id, position)
);

CREATE TABLE project_gallery (
    project_id BIGINT NOT NULL REFERENCES project (id) ON DELETE CASCADE,
    position   INT NOT NULL,
    media_id   VARCHAR(36) NOT NULL,
    PRIMARY KEY (project_id, position)
);

CREATE TABLE experience (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role          VARCHAR(160) NOT NULL,
    employer      VARCHAR(160) NOT NULL,
    location      VARCHAR(160),
    start_date    VARCHAR(30),
    end_date      VARCHAR(30),
    description   TEXT,
    display_order INT NOT NULL DEFAULT 0,
    visible       BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE experience_achievement (
    experience_id BIGINT NOT NULL REFERENCES experience (id) ON DELETE CASCADE,
    position      INT NOT NULL,
    text          VARCHAR(500) NOT NULL,
    PRIMARY KEY (experience_id, position)
);

CREATE TABLE experience_technology (
    experience_id BIGINT NOT NULL REFERENCES experience (id) ON DELETE CASCADE,
    position      INT NOT NULL,
    name          VARCHAR(60) NOT NULL,
    PRIMARY KEY (experience_id, position)
);

CREATE TABLE skill_category (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(80) NOT NULL,
    display_order INT NOT NULL DEFAULT 0
);

CREATE TABLE skill (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id   BIGINT NOT NULL REFERENCES skill_category (id) ON DELETE CASCADE,
    name          VARCHAR(60) NOT NULL,
    display_order INT NOT NULL DEFAULT 0
);
CREATE INDEX idx_skill_category ON skill (category_id);

CREATE TABLE resume_version (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_number    INT NOT NULL,
    label             VARCHAR(120),
    original_filename VARCHAR(255),
    storage_key       VARCHAR(80) NOT NULL,
    size_bytes        BIGINT NOT NULL,
    sha256            VARCHAR(64) NOT NULL,
    uploaded_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    published_at      TIMESTAMP WITH TIME ZONE,
    -- TRUE while published, NULL otherwise: UNIQUE then guarantees at most one published version.
    published_flag    BOOLEAN,
    CONSTRAINT uq_resume_version UNIQUE (version_number),
    CONSTRAINT uq_resume_storage_key UNIQUE (storage_key),
    CONSTRAINT uq_resume_published UNIQUE (published_flag)
);

CREATE TABLE profile_settings (
    id             BIGINT PRIMARY KEY,
    full_name      VARCHAR(120) NOT NULL,
    headline       VARCHAR(200),
    intro          TEXT,
    about          TEXT,
    interests      TEXT,
    highlights     TEXT,
    location       VARCHAR(120),
    contact_email  VARCHAR(254),
    github_url     VARCHAR(500),
    linkedin_url   VARCHAR(500),
    site_url       VARCHAR(500),
    contact_blurb  VARCHAR(500)
);

CREATE TABLE contact_message (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(120) NOT NULL,
    email      VARCHAR(254) NOT NULL,
    subject    VARCHAR(200) NOT NULL,
    message    TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    is_read    BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX idx_contact_created ON contact_message (created_at);
